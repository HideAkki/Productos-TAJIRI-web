-- Ejecutar con el propietario de la base. No modifica filas existentes.
create table if not exists public.gallery (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  image_url text not null check (image_url ~ '^https://'),
  date date not null default current_date,
  created_at timestamptz not null default now()
);
create index if not exists gallery_date_id_idx on public.gallery (date desc, id desc);
alter table public.gallery enable row level security;
revoke all on public.gallery from anon, authenticated;
grant select on public.gallery to anon, authenticated;
drop policy if exists "Public gallery read" on public.gallery;
create policy "Public gallery read" on public.gallery for select to anon, authenticated using (true);
